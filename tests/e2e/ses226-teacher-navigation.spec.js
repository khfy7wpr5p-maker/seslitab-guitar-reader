import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('SES-226 teacher tools stay above intake, preserve XML and remain accessible after reset', async ({ page }) => {
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  const nav = page.getByRole('tablist', { name: 'Öğretmen araçları' })
  await expect(nav).toBeVisible()
  const assignment = nav.getByRole('tab', { name: 'Ödev Gönder', exact: true })
  await assignment.click()
  await expect(page.locator('#teacher-auth-session-host')).toBeVisible()
  expect(await nav.evaluate(n => !!(n.compareDocumentPosition(document.querySelector('#input-section')) & Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true)
  await page.getByRole('tab', { name: 'TAB', exact: true }).click()
  await page.getByRole('button', { name: 'Örnek TAB yükle' }).click()
  await page.getByRole('button', { name: 'TAB metnini çevir' }).click()
  const xml = await page.locator('#xml-output').textContent()
  await page.locator('#xml-output').evaluate(n => { globalThis.__ses226Xml = n })
  for (const name of ['Gitar TAB', 'Keman', 'Ödev Gönder', 'Gitar TAB', 'Ödev Gönder']) {
    await nav.getByRole('tab', { name, exact: true }).click()
    await expect(page.locator('#tab-xml')).toBeVisible()
    await expect(page.locator('#xml-output')).toHaveText(xml)
    expect(await page.locator('#xml-output').evaluate(n => n === globalThis.__ses226Xml)).toBe(true)
  }
  await assignment.focus()
  await page.keyboard.press('ArrowRight')
  await expect(nav.getByRole('tab', { name: 'Gitar TAB', exact: true })).toBeFocused()
  await page.keyboard.press('End')
  await expect(nav.getByRole('tab', { name: 'Keman', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Tümünü sıfırla' }).click()
  await expect(page.locator('#xml-output')).toBeEmpty()
  await expect(nav).toBeVisible()
  await assignment.click()
  await expect(page.locator('#teacher-auth-session-host')).toBeVisible()
  await expect(page.locator('#tab-xml')).toBeVisible()
  expect(errors).toEqual([])
})

test('SES-226 real MusicXML/download survives navigation and reset invalidates the editor source', async ({ page }) => {
  test.setTimeout(120000)
  await page.goto('/')
  await page.locator('#musicxml-tab-btn').click()
  const bytes = await readFile(new URL('../fixtures/gtab10c/smoosic-like-source.musicxml', import.meta.url))
  await page.locator('#musicxml-file-input').setInputFiles({ name: 'source.musicxml', mimeType: 'application/xml', buffer: bytes })
  await page.locator('#musicxml-open-btn').click()
  await expect(page.locator('#xml-output')).toContainText('<score-partwise')
  const source = await page.locator('#xml-output').textContent()
  await page.locator('#smoosic-tab-btn').click()
  await expect(page.locator('#smoosic-panel')).toBeVisible()
  await expect(page.frameLocator('#smoosic-editor-frame').locator('#poc-status')).toHaveAttribute('data-loaded-file-name', 'source.musicxml', { timeout: 60000 })
  const nav = page.getByRole('tablist', { name: 'Öğretmen araçları' })
  for (const name of ['Gitar TAB', 'Keman', 'Ödev Gönder']) {
    await nav.getByRole('tab', { name, exact: true }).click()
    await expect(page.locator('#tab-xml')).toBeVisible()
    await expect(page.locator('#musicxml-download-btn')).toBeVisible()
    await expect(page.locator('#omr-download-btn')).toBeHidden()
  }
  // Actual score-view listener used by the production entry point.
  await page.locator('#result-score-view-btn').click()
  await expect(page.locator('#tab-xml')).toBeVisible()
  await expect(nav.getByRole('tab', { name: 'Ödev Gönder', exact: true })).toHaveAttribute('aria-selected', 'false')
  await page.locator('#result-xml-btn').click()
  await expect(page.locator('#tab-xml')).toBeVisible()
  await nav.getByRole('tab', { name: 'Ödev Gönder', exact: true }).click()
  await expect(page.locator('#tab-score-view')).toBeHidden()
  const download = page.waitForEvent('download')
  await page.locator('#musicxml-download-btn').click()
  expect(await readFile(await (await download).path(), 'utf8')).toBe(source)
  await page.getByRole('button', { name: 'Tümünü sıfırla' }).click()
  await expect(page.locator('#xml-output')).toBeEmpty()
  await expect(page.locator('#musicxml-download-btn')).toBeHidden()
  await expect(page.locator('#smoosic-editor-host-status')).toContainText('MusicXML')
  await expect(page.locator('#smoosic-editor-frame')).toBeHidden()
  await expect(nav).toBeVisible()
})
